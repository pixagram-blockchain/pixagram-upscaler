// Generates depixelize-wasm.inline.js: a classic <script> (no ES modules, no
// fetch) with both .wasm builds embedded as gzip + base64. It works from
// file:// pages and anywhere a separate .wasm request is inconvenient, and
// exposes the default export of depixelize-wasm.mjs as `DepixelizeWasm`.
//
//   node make-inline.mjs depixelize-wasm.mjs depixelize.wasm depixelize-simd.wasm out.js

import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const [gluePath, scalarPath, simdPath, outPath] = process.argv.slice(2);
if (!outPath) throw new Error('usage: make-inline.mjs <glue.mjs> <scalar.wasm> <simd.wasm> <out.js>');

let src = readFileSync(gluePath, 'utf8');
const header = src.slice(0, src.indexOf('\nconst DEFAULTS'));
src = src.slice(header.length + 1);

// Default source → the embedded bytes.
const hook = /\/\/ @default-source[^\n]*\n[\s\S]*?\/\/ @end\n/;
if (!hook.test(src)) throw new Error('make-inline: @default-source block not found');
src = src.replace(hook, `function defaultSource(simd) {
  return inflate(simd ? WASM_SIMD : WASM_SCALAR);
}
`);
// ES module syntax → plain declarations.
src = src
  .replace(/^export default api;\n/m, '')
  .replace(/^export \{ DEFAULTS \};\n/m, '')
  .replace(/^export (async function|function|const) /gm, '$1 ');
for (const bad of ['export ', 'import.meta']) {
  if (src.includes(bad)) throw new Error(`make-inline: unexpected "${bad}" left in the glue`);
}

const b64 = (p) => gzipSync(readFileSync(p), { level: 9 }).toString('base64');

const out = `// depixelize-wasm.inline.js — classic-script build of depixelize-wasm.mjs with
// both .wasm modules embedded (gzip + base64), for pages served from file:// or
// without a bundler. Needs DecompressionStream (Chrome 80, Firefox 113,
// Safari 16.4, Node 18). Generated by make-inline.mjs — do not edit.
//
//   <script src="depixelize-wasm.inline.js"></script>
//   await DepixelizeWasm.init();
//   const svg = DepixelizeWasm.depixelize(imageData, { scale: 30 });
//
// API: see depixelize-wasm.mjs / depixelize-wasm.d.ts.
(function (global) {
'use strict';
const WASM_SCALAR = '${b64(scalarPath)}';
const WASM_SIMD = '${b64(simdPath)}';

async function inflate(b64) {
  if (typeof DecompressionStream !== 'function') {
    throw new Error('depixelize-wasm.inline: DecompressionStream is not available; use depixelize-wasm.mjs');
  }
  const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  const stream = new Blob([bin]).stream().pipeThrough(new DecompressionStream('gzip'));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

${src}
global.DepixelizeWasm = api;
})(typeof globalThis !== 'undefined' ? globalThis : self);
`;
writeFileSync(outPath, out);
console.log(`${outPath}: ${(out.length / 1024).toFixed(0)} KiB`);
